function evidenceLines(record: MemoryRecord): string[] {
  const e = record.evidence;
  return e ? [
    `Evidence recorded: ${e.recordedAt}; session: ${e.sessionId}`,
    ...e.files.map(f => `- File: ${f.path} (sha256 ${f.sha256})`),
    ...e.checks.map(c => `- Reported check (not automatically rerun): ${c}`),
    ...e.sources.map(s => `- Source: ${s}`),
    ...(e.observedChecks ?? []).map(r => `- Host receipt ${r.id}: ${r.phase}; exit=${r.exitCode ?? "unknown"}; expected tests executed=unknown; command digest=${r.commandDigest}`),
  ] : ["Evidence: none recorded."];
}

async function save(root: string, state: ProjectMemory): Promise<void> {
  const dir = (await directory(root, true))!;
  const freshness = await assessFreshness(root, state, reminderRecords(state));
  const header = `${GENERATED}\n\nRevision: ${state.revision}. Freshness is checked for the bounded working set; other records are unverified here. project_memory read by id recomputes individual evidence.\n`;
  const task = state.task;
  const taskDoc = `${header}\n# Current task\n\n${task ? [
    task.text, `\nStatus: ${task.status}; evidence: ${freshness.get(task.id)?.status ?? "unverified"}`,
    "\n## Scope", ...(task.scope ?? []).map(s => `- ${s}`), "\n## Acceptance criteria", ...(task.acceptanceCriteria ?? []).map(s => `- ${s}`), "\n## Progress", ...task.progress.map(s => `- ${s}`), "\n## Next steps", ...task.nextSteps.map(s => `- ${s}`),
    "\n## Blockers", ...(task.blockers ?? []).map(s => `- ${s}`), "\n## Evidence", ...evidenceLines(task), ...(task.invalidated ? [`Invalidated: ${task.invalidated}`] : []),
  ].join("\n") : "No task recorded."}\n`;
  const decisionsDoc = `${header}\n# Decision log\n\n${state.decisions.map(d => [
    `## ${d.id} — ${freshness.get(d.id)?.status ?? (d.supersededBy ? "superseded" : d.invalidated ? "stale" : "unverified")}`, d.text, `Updated: ${d.updatedAt}`,
    ...(d.supersededBy ? [`Superseded by: ${d.supersededBy}`] : []),
    ...(d.invalidated ? [`Invalidated: ${d.invalidated}`] : []), ...evidenceLines(d),
  ].join("\n\n")).join("\n\n")}\n`;
  // These names belong to this feature only. Never overwrite user-authored docs.
  for (const name of ["TASK.md", "DECISIONS.md"]) {
    const existing = await safeRead(join(dir, name), MAX_STATE_BYTES);
    if (existing !== null && !existing.startsWith(GENERATED)) fail(`${name} is user-authored; refusing to overwrite it`);
  }
  const serialized = JSON.stringify(state, null, 2) + "\n";
  if ([serialized, taskDoc, decisionsDoc].some(s => Buffer.byteLength(s) > MAX_STATE_BYTES)) fail("memory exceeds the 2 MiB limit; preserve/archive source deliberately before further updates");
  await atomicWrite(join(dir, "TASK.md"), redactSecrets(taskDoc));
  await atomicWrite(join(dir, "DECISIONS.md"), redactSecrets(decisionsDoc));
  // Source of truth commits last; interrupted generated views can be refreshed.
  await atomicWrite(join(dir, "memory.json"), serialized);
}

/** Filesystem lock + expectedRevision protect independent omp sessions. No model calls. */
export async function updateMemory(root: string, change: MemoryChange, sessionId: string, observedChecks: CheckReceipt[] = []): Promise<ProjectMemory> {
  validateChange(change);
  const dir = (await directory(root, true))!;
  const lock = join(dir, "write.lock");
  try { await mkdir(lock); } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "EEXIST") fail("write.lock exists: another writer may be active; inspect before removing a leftover lock");
    throw error;
  }
  try {
    const state = await readMemory(root) ?? emptyMemory();
    if (state.revision !== change.expectedRevision) fail(`revision conflict: expected ${change.expectedRevision}, current ${state.revision}; read again before updating`);
    if (observedChecks.some(r => !validReceipt(r) || r.sessionId !== sessionId || r.phase === "requested")) fail("invalid or cross-session observed check receipt");
    const evidence = await capture(root, change, sessionId, observedChecks);
    state.version = 2; state.taskHistory ??= [];
    if (state.task && !state.task.taskId) state.task.taskId = `legacy-task-${state.revision}`;
    const now = new Date().toISOString();
    const existing = change.id === "task" ? state.task : state.decisions.find(d => d.id === change.id);
    if (state.task?.pendingGoalChange && change.pendingGoalChange === null && !change.reason?.trim()) fail("clearing a pending goal change requires a reason");
    if (change.action === "supersede" && change.id === "task" && !state.task) fail("no task to supersede");
    const attribution = change.provenance ?? { kind: "model_plan" as const, source: `agent project_memory operation; session:${sessionId}` };
    const archiveTask = (reason: string, replacement?: string) => {
      if (!state.task) return;
      let id = `task-history-r${state.revision}`;
      while ([...state.taskHistory!, ...state.decisions].some(r => r.id === id)) id += "-old";
      state.taskHistory!.push({ ...structuredClone(state.task), id, archivedAt: now, archiveReason: reason, ...(replacement ? { supersededBy: replacement } : {}) });
    };
    const taskSupersession = change.action === "supersede" && change.id === "task";
    if (change.action === "set_task" || taskSupersession) {
      const replaced = taskSupersession || !state.task || state.task.text !== change.text || state.task.status === "done" || !!state.task.invalidated;
      let taskId = replaced ? `task-${state.revision + 1}` : state.task!.taskId!;
      if (replaced) {
        const used = new Set([...state.decisions.map(d => d.id), ...(state.taskHistory ?? []).flatMap(t => [t.id, t.taskId]), state.task?.taskId]);
        while (used.has(taskId)) taskId += "-new";
      }
      archiveTask(replaced ? "superseded" : "updated", replaced ? taskId : undefined);
      state.task = { id: "task", taskId, text: change.text!, status: change.status ?? "active", progress: change.progress ?? [], nextSteps: change.nextSteps ?? [], blockers: change.blockers ?? [],
        scope: change.scope ?? [], acceptanceCriteria: change.acceptanceCriteria ?? [], hypotheses: change.hypotheses ?? [],
        pendingGoalChange: change.pendingGoalChange === undefined && !replaced ? state.task?.pendingGoalChange : change.pendingGoalChange,
        provenance: change.provenance ?? (!replaced ? state.task?.provenance : undefined) ?? attribution, updatedAt: now, evidence };
    } else if (change.action === "update_task" || change.action === "complete_task") {
      if (!state.task) fail("no task to update");
      if (change.text !== undefined && change.text !== state.task.text) fail("use set_task or supersede id=task to change the objective");
      if (change.status !== undefined && change.status !== "done" && (state.task.status === "done" || state.task.invalidated)) fail("use set_task for an explicit new objective; an update cannot reactivate this task");
      if (change.pendingGoalChange === null && state.task.pendingGoalChange && !change.reason?.trim()) fail("clearing a pending goal change requires a reason");
      archiveTask(change.action === "complete_task" ? "completed" : "updated");
      for (const key of ["progress", "nextSteps", "blockers", "scope", "acceptanceCriteria", "hypotheses", "pendingGoalChange", "provenance", "status"] as const) {
        if (change[key] !== undefined) Object.assign(state.task, { [key]: change[key] });
      }
      if (change.action === "complete_task") state.task.status = "done";
      if (evidence) state.task.evidence = evidence;
      state.task.updatedAt = now;
    } else if (change.action === "record_decision" || change.action === "supersede") {
      if (change.action === "supersede" && (!existing || existing.id === "task" || existing.supersededBy)) fail("supersede requires an active decision ID");
      const id = `d-${state.revision + 1}`;
      state.decisions.push({ id, text: change.text!, updatedAt: now, evidence, provenance: attribution, taskId: state.task?.taskId, ...(existing?.pinned ? { pinned: true } : {}) });
      if (change.action === "supersede") existing!.supersededBy = id;
    } else {
      if (!existing) fail("record not found");
      if (existing.id === "task") archiveTask(change.action);
      if (change.action === "pin" || change.action === "unpin") existing.pinned = change.action === "pin";
      else if (change.action === "invalidate") existing.invalidated = change.reason;
      else {
        if (!evidence || (!evidence.files.length && !evidence.checks.length && !evidence.observedChecks?.length)) fail("verify requires file evidence or reported checks");
        existing.evidence = evidence;
        delete existing.invalidated;
      }
      existing.updatedAt = now;
    }
    if (state.task && (["set_task", "update_task", "complete_task"].includes(change.action) || change.id === "task")) {
      state.task.lastChange = { operation: change.action, reason: change.reason, sessionId, at: now };
    }
    state.revision++;
    await save(root, state);
    return state;
  } finally { await rm(lock, { recursive: true }); }
}

export async function refreshDocuments(root: string): Promise<ProjectMemory> {
  const dir = await directory(root);
  if (!dir) fail("no project memory yet; use project_memory set_task first");
  const lock = join(dir, "write.lock");
  await mkdir(lock);
  try {
    const state = await readMemory(root);
    if (!state) fail("no project memory yet");
    await save(root, state);
    return state;
  } finally { await rm(lock, { recursive: true }); }
}

export function reminderRecords(state: ProjectMemory): MemoryRecord[] {
  const words = new Set((state.task?.text.toLowerCase().match(/[\p{L}\p{N}_./-]{3,}/gu) ?? []));
  const score = (record: MemoryRecord, i: number) => (record.pinned ? 1000 : 0) +
    Math.min(20, [...new Set(record.text.toLowerCase().match(/[\p{L}\p{N}_./-]{3,}/gu) ?? [])].filter(w => words.has(w)).length * 2) + i / Math.max(1, state.decisions.length);
  const decisions = state.decisions.map((record, i) => ({ record, score: score(record, i) }))
    .filter(({ record }) => !record.supersededBy && !record.invalidated && (!record.taskId || record.taskId === state.task?.taskId || record.pinned))
    .sort((a, b) => b.score - a.score).slice(0, 8).map(x => x.record);
  return [...(state.task ? [state.task] : []), ...decisions];
}

/** Bounded JSON on every tool call; the full source is never returned implicitly. */
export async function memoryView(root: string, state: ProjectMemory, options: { id?: string; offset?: number; limit?: number; section?: "decisions" | "tasks" } = {}): Promise<string> {
  const offset = options.offset ?? 0, limit = options.limit ?? 5;
  if (!Number.isInteger(offset) || offset < 0 || !Number.isInteger(limit) || limit < 1 || limit > 10) fail("read offset/limit must be nonnegative integers; limit is 1–10");
  const history = [...(state.taskHistory ?? [])].reverse();
  const record = options.id ? (options.id === "task" ? state.task : state.decisions.find(d => d.id === options.id) ?? (state.task?.taskId === options.id ? state.task : undefined) ?? history.find(t => t.id === options.id || t.taskId === options.id)) : undefined;
  if (options.id && !record) fail("record not found");
  const records = record ? [record] : options.section === "tasks" ? history.slice(offset, offset + limit) : [...(state.task ? [state.task] : []), ...state.decisions.slice().reverse().slice(offset, offset + limit)];
  const freshness = await assessFreshness(root, state, records);
  const clip = (s: string, max: number) => s.length <= max ? s : s.slice(0, max) + "…";
  const summarize = (r: MemoryRecord) => ({
    id: r.id, text: clip(r.text, record ? 2000 : 400), updatedAt: r.updatedAt,
    provenance: r.provenance ? { kind: r.provenance.kind, source: clip(r.provenance.source, 250) } : undefined, taskId: r.taskId, pinned: r.pinned ?? false, invalidated: r.invalidated, supersededBy: r.supersededBy,
    freshness: freshness.get(r.id),
    ...("status" in r ? { status: (r as Task).status, progress: (r as Task).progress.slice(-3).map(s => clip(s, 300)), nextSteps: (r as Task).nextSteps.slice(0, 3).map(s => clip(s, 300)), blockers: ((r as Task).blockers ?? []).slice(0, 3).map(s => clip(s, 300)), scope: (r as Task).scope?.slice(0, 3).map(s => clip(s, 300)), acceptanceCriteria: (r as Task).acceptanceCriteria?.slice(0, 3).map(s => clip(s, 300)),
      hypotheses: (r as Task).hypotheses?.slice(0, 3).map(h => ({ text: clip(h.text, 300), status: h.status, sources: h.sources.slice(0, 3).map(s => clip(s, 100)) })), pendingGoalChange: (r as Task).pendingGoalChange ? { text: clip((r as Task).pendingGoalChange!.text, 400), source: clip((r as Task).pendingGoalChange!.source, 150) } : null, archiveReason: (r as Task).archiveReason, lastChange: (r as Task).lastChange } : {}),
    evidence: r.evidence ? {
      recordedAt: r.evidence.recordedAt, sessionId: r.evidence.sessionId,
      files: r.evidence.files.slice(0, 3).map(f => ({ path: clip(f.path, 150), sha256: f.sha256 })),
      checks: r.evidence.checks.slice(0, 3).map(s => clip(s, 250)),
      freshnessScope: r.evidence.freshnessScope ?? "legacy repository", observedChecks: r.evidence.observedChecks?.slice(-3),
      sources: r.evidence.sources.slice(0, 3).map(s => clip(s, 150)),
    } : null,
  });
  const payload = {
    root, version: state.version, revision: state.revision, records: records.map(summarize),
    totalDecisions: state.decisions.length, totalTaskSnapshots: history.length,
    nextOffset: !record && offset + limit < (options.section === "tasks" ? history.length : state.decisions.length) ? offset + limit : null,
    note: "Bounded previews; read by id or page offset. Full evidence/progress lists remain in .context-forge/memory.json; use bounded file reads for omitted details.",
  };
  while (JSON.stringify(payload).length > 12000 && payload.records.length > 1) {
    payload.records.pop();
    payload.nextOffset = offset + Math.max(0, payload.records.length - (options.section !== "tasks" && state.task ? 1 : 0));
  }
  const json = JSON.stringify(payload, (_key, value) => typeof value === "string" ? redactSecrets(value) : value, 2);
  return json.length <= 16000 ? json : JSON.stringify({ revision: state.revision, root, note: "Record metadata exceeds the tool budget; use a bounded read of .context-forge/memory.json." });
}

export function renderReminder(state: ProjectMemory, freshness: Map<string, Freshness>): string {
  return renderHandoff(state, freshness, { budget: 8000, selected: reminderRecords(state) }).text;
}
